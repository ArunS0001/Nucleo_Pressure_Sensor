/*
 * STM32 HAL port for ad7732_pressure.c (NUCLEO-G491RE, project TEST_1409)
 *
 *   SPI1 : PA5 SCK, PA6 MISO, PA7 MOSI, 8-bit, master, CPOL=High, CPHA=2 Edge
 *   CS   : PC7  (label ADC_CS)
 *   RDY  : PA9  (label ADC_RDY), EXTI9 falling edge, pull-up  -> EXTI9_5_IRQn
 */
#include "main.h"
#include <stdint.h>
#include <stdbool.h>
#include "ad7732_pressure.h"

extern SPI_HandleTypeDef hspi1;          /* generated by MX_SPI1_Init() */

uint8_t spi_xfer(uint8_t tx)
{
    uint8_t rx = 0xFF;
    HAL_SPI_TransmitReceive(&hspi1, &tx, &rx, 1, 10);
    return rx;
}

void spi_xfer_buf(const uint8_t *tx, uint8_t *rx, uint16_t len)
{
    HAL_SPI_TransmitReceive(&hspi1, (uint8_t *)tx, rx, len, 5);
}

void ad7732_cs(bool select)
{
    HAL_GPIO_WritePin(ADC_CS_GPIO_Port, ADC_CS_Pin,
                      select ? GPIO_PIN_RESET : GPIO_PIN_SET);
}

void ad7732_irq_disable(void) { HAL_NVIC_DisableIRQ(EXTI9_5_IRQn); }
void ad7732_irq_enable(void)  { HAL_NVIC_EnableIRQ(EXTI9_5_IRQn);  }

void delay_ms(uint32_t ms)
{
    HAL_Delay(ms);
}
